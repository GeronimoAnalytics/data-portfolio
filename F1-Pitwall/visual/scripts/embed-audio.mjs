#!/usr/bin/env node
/**
 * Embed a local audio clip into the visual bundle as a base64 data URI.
 *
 *   node scripts/embed-audio.mjs assets/max_radio_rage.mp3
 *   node scripts/embed-audio.mjs --clear          # back to synthesized bleeps only
 *
 * Writes src/audio/radioClip.ts. A .pbiviz package only contains the compiled JS/CSS and the
 * icon, so media must be inlined. Keep clips short (< 1 MB) - they inflate the visual size.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { extname, resolve } from "node:path";

const out = resolve("src/audio/radioClip.ts");
const arg = process.argv[2] ?? "assets/max_radio_rage.mp3";
const header = "// AUTO-GENERATED by scripts/embed-audio.mjs - do not edit by hand.\n";

if (arg === "--clear") {
    writeFileSync(out, `${header}export const RADIO_CLIP_DATA_URI = "";\n`);
    console.log("radio clip cleared -> synthesized bleeps only");
    process.exit(0);
}
if (!existsSync(arg)) {
    console.error(`audio file not found: ${arg}`);
    process.exit(1);
}
const mime = { ".mp3": "audio/mpeg", ".wav": "audio/wav", ".ogg": "audio/ogg", ".m4a": "audio/mp4" }[extname(arg).toLowerCase()];
if (!mime) { console.error("use .mp3, .wav, .ogg or .m4a"); process.exit(1); }
const b64 = readFileSync(arg).toString("base64");
writeFileSync(out, `${header}export const RADIO_CLIP_DATA_URI = "data:${mime};base64,${b64}";\n`);
console.log(`embedded ${arg} (${(b64.length / 1024).toFixed(0)} KB base64) -> ${out}`);
