// Inlines Titillium Web (SIL Open Font License) into style/fonts.less as base64 @font-face rules.
// Power BI visuals cannot load web fonts from a CDN, so the font has to travel inside the package.
import { readFileSync, writeFileSync } from "node:fs";
const dir = "node_modules/@fontsource/titillium-web/files";
const faces = [["400", "normal"], ["600", "normal"], ["700", "normal"], ["900", "normal"], ["700", "italic"]];
let out = "// AUTO-GENERATED by scripts/embed-fonts.mjs - Titillium Web, SIL Open Font License 1.1\n";
for (const [w, s] of faces) {
    const b64 = readFileSync(`${dir}/titillium-web-latin-${w}-${s}.woff2`).toString("base64");
    out += `@font-face { font-family: "Titillium Web"; font-style: ${s}; font-weight: ${w}; font-display: block; src: url(data:font/woff2;base64,${b64}) format("woff2"); }\n`;
}
writeFileSync("style/fonts.less", out);
console.log(`style/fonts.less written (${(out.length / 1024).toFixed(0)} KB)`);
